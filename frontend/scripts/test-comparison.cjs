const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ts=require('typescript');
const source=fs.readFileSync(path.join(__dirname,'../lib/comparison.ts'),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2019}}).outputText;
const output={exports:{}};vm.runInNewContext(compiled,{module:output,exports:output.exports});
const {addToComparison}=output.exports;
let items=[];
for(let i=1;i<=4;i++)items=addToComparison(items,{sku:'CPU'+i,category_id:'CPU'}).items;
assert.equal(items.length,4);
assert.ok(addToComparison(items,{sku:'CPU5',category_id:'CPU'}).error);
assert.ok(addToComparison(items,{sku:'RAM1',category_id:'RAM'}).error);
items=addToComparison(items,{sku:'CPU1',category_id:'CPU'}).items;
assert.equal(items.length,3);assert.ok(!items.some(item=>item.sku==='CPU1'));
items=addToComparison(items,{sku:'CPU5',category_id:'CPU'}).items;
assert.equal(items.length,4);assert.equal(items[3].sku,'CPU5');
assert.equal(addToComparison([],{sku:'RAM1',category_id:'RAM'}).items[0].category_id,'RAM');
console.log('Comparison selection: category guard, 4-item cap, toggle/remove and re-add passed.');
